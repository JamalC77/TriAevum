inline const Glyph5x7& font5x7_glyph(char c) {
    if (c >= 'a' && c <= 'z')
        c = static_cast<char>(c - 'a' + 'A');
    const Glyph5x7* question = nullptr;
    for (const Glyph5x7& g : kFont5x7) {
        if (g.ch == c)
            return g;
        if (g.ch == '?')
            question = &g;
    }
    return *question;
}
